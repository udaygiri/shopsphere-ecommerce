from typing import Optional
from pydantic import BaseModel, Field, ConfigDict
from app.schemas.order import OrderResponse


class PaymentOrderCreate(BaseModel):
    shipping_address: str = Field(
        ...,
        min_length=10,
        max_length=500,
        description="Delivery address (minimum 10 characters)",
    )


class PaymentOrderResponse(BaseModel):
    razorpay_order_id: str
    amount: int  # Amount in paise (1 INR = 100 paise)
    currency: str = "INR"
    key_id: str
    amount_in_rupees: float
    shipping_address: str
    customer_name: Optional[str] = None
    customer_email: Optional[str] = None
    is_mock: bool = False

    model_config = ConfigDict(from_attributes=True)


class PaymentVerifyRequest(BaseModel):
    razorpay_order_id: str = Field(..., description="Order ID generated by Razorpay")
    razorpay_payment_id: str = Field(..., description="Payment ID returned by Razorpay Checkout modal")
    razorpay_signature: str = Field(..., description="Cryptographic HMAC-SHA256 signature from Razorpay")
    shipping_address: Optional[str] = Field(None, min_length=10, max_length=500, description="Optional override/fallback shipping address")


class PaymentVerifyResponse(BaseModel):
    success: bool = True
    message: str = "Payment successfully verified and order confirmed"
    order: OrderResponse
